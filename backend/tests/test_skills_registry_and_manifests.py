"""Tests for SkillRegistry, SemVer validation, dependency cycle detection, and manifest rules."""

import pytest
from app.skills.catalog import create_default_skills
from app.skills.registry import SkillRegistry
from app.skills.schemas import (
    SkillCategory,
    SkillHealthStatus,
    SkillManifest,
    SkillRiskLevel,
    SkillSource,
)


@pytest.fixture
def empty_registry() -> SkillRegistry:
    """Provide a fresh empty registry for isolated testing."""
    return SkillRegistry()


@pytest.fixture
def populated_registry() -> SkillRegistry:
    """Provide registry populated with canonical built-in skills."""
    reg = SkillRegistry()
    for skill in create_default_skills():
        reg.register(skill)
    return reg


def test_registry_register_and_lookup(empty_registry: SkillRegistry) -> None:
    """Ensure valid trusted skill registers and can be retrieved."""
    manifest = SkillManifest(
        id="test.sample",
        name="Sample Test Skill",
        description="A sample skill for testing registry behavior.",
        version="1.0.0",
        category=SkillCategory.RESEARCH,
        risk_level=SkillRiskLevel.READ_ONLY,
        required_tools=["web_search"],
        required_permissions=["web.read"],
        source=SkillSource.BUILTIN,
    )
    empty_registry.register(manifest)

    retrieved = empty_registry.get("test.sample")
    assert retrieved is not None
    assert retrieved.name == "Sample Test Skill"
    assert retrieved.version == "1.0.0"
    assert retrieved.enabled is True


def test_registry_rejects_duplicate_registration(empty_registry: SkillRegistry) -> None:
    """Ensure duplicate skill IDs cannot be registered."""
    manifest = SkillManifest(
        id="test.duplicate",
        name="Duplicate Skill",
        description="Testing duplicate collision.",
        version="1.0.0",
        category=SkillCategory.RESEARCH,
        risk_level=SkillRiskLevel.READ_ONLY,
        source=SkillSource.BUILTIN,
    )
    empty_registry.register(manifest)

    with pytest.raises(ValueError) as exc:
        empty_registry.register(manifest)
    assert "already registered" in str(exc.value)


