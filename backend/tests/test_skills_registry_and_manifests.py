def test_registry_detects_dependency_cycles(empty_registry: SkillRegistry) -> None:
    """Ensure dependency cycles between skills are rejected (Section 60)."""
    skill_a = SkillManifest(
        id="chain.a",
        name="Chain A",
        description="A depends on B",
        version="1.0.0",
        category=SkillCategory.RESEARCH,
        risk_level=SkillRiskLevel.READ_ONLY,
        dependencies=["chain.b"],
        source=SkillSource.BUILTIN,
    )
    skill_b = SkillManifest(
        id="chain.b",
        name="Chain B",
        description="B depends on A",
        version="1.0.0",
        category=SkillCategory.RESEARCH,
        risk_level=SkillRiskLevel.READ_ONLY,
        dependencies=["chain.a"],
        source=SkillSource.BUILTIN,
    )

    empty_registry.register(skill_a)
    with pytest.raises(ValueError) as exc:
        empty_registry.register(skill_b)
    assert "circular" in str(exc.value).lower() or "cycle" in str(exc.value).lower()


def test_registry_enable_and_disable(populated_registry: SkillRegistry) -> None:
    """Ensure skills can be enabled or disabled via backend governance."""
    skill_id = "computer.assist"
    assert populated_registry.is_enabled(skill_id) is False  # Disabled by default for safety

    # Enable
    updated = populated_registry.set_enabled(skill_id, True)
    assert updated.enabled is True
    assert populated_registry.is_enabled(skill_id) is True

    # Disable
    updated = populated_registry.set_enabled(skill_id, False)
    assert updated.enabled is False
    assert populated_registry.is_enabled(skill_id) is False


def test_registry_health_computation(populated_registry: SkillRegistry) -> None:
    """Ensure health status accurately reflects tool availability."""
    # When available_tools is empty, skills with required tools should be DEGRADED or UNAVAILABLE
    health = populated_registry.get_health("research.web", available_tools=set())
    assert health in (SkillHealthStatus.DEGRADED, SkillHealthStatus.UNAVAILABLE)

    # When all required tools are available, health should be HEALTHY
    skill = populated_registry.get("research.web")
    assert skill is not None
    health_ok = populated_registry.get_health("research.web", available_tools=set(skill.required_tools))
    assert health_ok == SkillHealthStatus.HEALTHY


